import { connect } from './cdp.mjs';
import { injectSetters, waitForText, setFileInput, clickText, typeAutocomplete, sleep } from './cdp-extra.mjs';
const p = await connect({ port: 9222 });
await p.send('Emulation.setDeviceMetricsOverride', { width: 1280, height: 800, deviceScaleFactor: 1, mobile: false });
await p.navigate('http://localhost:8791/hhh-login');
await sleep(2500);
await injectSetters(p);
await typeAutocomplete(p, 'username', 'demo-rcm-hhah');
await sleep(300);
await typeAutocomplete(p, 'current-password', 'DemoAgency!2026');
await sleep(300);
await clickText(p, 'button', 'Login');
const ok = await waitForText(p, 'Bulk Upload', { timeout: 15000 });
console.log('reached upload page:', ok);
await injectSetters(p);
const fileCount = await p.evaluate("document.querySelectorAll('input[type=file]').length");
console.log('file inputs:', fileCount);
await setFileInput(p, 0, ['/Users/sujaygp/Desktop/poc/docs/_demo-upload.xlsx']);
await sleep(500);
await setFileInput(p, 1, ['/Users/sujaygp/Desktop/poc/docs/_demo-upload-unsigned.zip']);
await sleep(500);
const clicked = await clickText(p, 'button', 'Start Upload');
console.log('clicked Start Upload:', clicked);
const started = await waitForText(p, 'Upload started', { timeout: 20000 });
console.log('upload started msg:', started);
await sleep(500);
p.close(); process.exit(0);
